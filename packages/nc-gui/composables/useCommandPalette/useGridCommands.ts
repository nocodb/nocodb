import {
  type ButtonType,
  type ColumnType,
  PermissionEntity,
  PermissionKey,
  UITypes,
  isAIPromptCol,
  isAutoGeneratedColumn,
  isLinksOrLTAR,
  isSystemColumn,
  isVirtualCol,
} from 'nocodb-sdk'
import type { CmdCommand, Row } from '~/lib/types'
import type { CmdGridDeps, CmdGridSelectionDeps, CmdRecordExtras } from '~/lib/cmdPaletteTypes'

/** Cmd+K on checked rows is EE: CE adds no selection context, so nothing is checked for the selection bar. */
export function useGridSelectionCommands(_deps: CmdGridSelectionDeps) {
  return { count: computed(() => 0), clear: () => {} }
}

/**
 * Cmd+K for the grid: the active cell's record as a context chip (Backspace steps back to the view),
 * gated like the cell context menu's row items. Checked rows, a cell range or a selected header take over.
 * `recordExtras` lets the EE edition add rows and typed edits to that record.
 */
export function useGridCommands(
  g: CmdGridDeps,
  recordExtras?: (row: Row, path: Array<number>, section: string) => CmdRecordExtras,
) {
  const { t } = useI18n()

  const route = useRoute()

  const { $api } = useNuxtApp()

  const { isUIAllowed, isDataReadOnly } = useRoles()

  const { isMobileMode, appInfo } = useGlobal()

  const { isAllowed: isPermissionAllowed } = usePermissions()

  const { dashboardUrl } = useDashboard()

  const { copy: copyToClipboard } = useCopy()

  const { activeWorkspaceId } = storeToRefs(useWorkspace())

  const { isExpandedFormCommentMode } = storeToRefs(useConfigStore())

  const { meta, view, columns, activeCell, selection, getDataCache, interfacePageDataApi } = g

  useCommandProvider(
    () => `grid-active-row:${view.value?.id}`,
    'record',
    () => {
      const cell = activeCell.value
      if (g.isPublicView.value || !cell || cell.row === undefined || cell.row < 0) return { commands: [] }
      if (
        (!selection.value.isEmpty() && !selection.value.isSingleCell()) ||
        g.selectedHeaderColumnIds.value.size ||
        g.selectedAllRecords.value ||
        [getDataCache(), ...g.groupDataCache.value.values()].some((cache) => cache.selectedRows.value.length)
      )
        return { commands: [] }

      const path = cell.path ?? []
      const row = getDataCache(path)?.cachedRows.value.get(cell.row)
      if (!row) return { commands: [] }

      const section = t('labels.commandPalette.sections.record')
      const rowId = extractPkFromRow(row.row, meta.value?.columns as ColumnType[])
      const extras = recordExtras?.(row, path, section)
      const canInsert =
        g.isAddingEmptyRowAllowed.value &&
        isUIAllowed('dataEdit') &&
        !isDataReadOnly.value &&
        !meta.value?.synced &&
        (!interfacePageDataApi || interfacePageDataApi.canAddDeleteInline.value) &&
        (!meta.value?.id || isPermissionAllowed(PermissionEntity.TABLE, meta.value.id, PermissionKey.TABLE_RECORD_ADD))
      const context = { row: cell.row, col: cell.column ?? 0, path }

      const commands: CmdCommand[] = [
        {
          id: 'record:expand',
          priority: CMD_PRIORITY.primary,
          title: t('labels.commandPalette.record.expand'),
          section,
          icon: { type: 'icon', name: 'ncMaximize2' },
          keywords: ['open', 'record'],
          shortcut: ['Space'],
          run: () => g.expandForm(row, undefined, false, path),
        },
      ]

      if (canInsert) {
        commands.push({
          id: 'record:insert-above',
          priority: CMD_PRIORITY.normal,
          title: t('general.insertAbove'),
          section,
          icon: { type: 'icon', name: 'ncChevronUp' },
          keywords: ['add', 'new', 'row'],
          run: () => g.addRow(context, 'above'),
        })
        if (!g.isInsertBelowDisabled.value) {
          commands.push({
            id: 'record:insert-below',
            priority: CMD_PRIORITY.normal,
            title: t('general.insertBelow'),
            section,
            icon: { type: 'icon', name: 'ncChevronDown' },
            keywords: ['add', 'new', 'row'],
            run: () => g.addRow(context, 'below'),
          })
        }
      }

      if (rowId && !interfacePageDataApi) {
        commands.push({
          id: 'record:copy-url',
          priority: CMD_PRIORITY.normal,
          title: t('labels.commandPalette.copyRecordUrl'),
          section,
          icon: { type: 'icon', name: 'ncLink' },
          feedback: t('labels.commandPalette.copied'),
          // Same URL shape as the expanded form's "Copy record URL".
          run: () =>
            copyToClipboard(
              encodeURI(
                `${dashboardUrl.value}/${route.params.typeOrId}/${route.params.baseId}/${meta.value?.id}${
                  view.value?.id ? `/${view.value.id}` : ''
                }?rowId=${rowId}${path.length ? `&path=${path.join('-')}` : ''}`,
              ),
            ),
        })
      }

      // Duplicate and delete use the cell context menu's row gates (interface pages: add_delete_inline only).
      const canAddDeleteRows =
        isUIAllowed('dataEdit') &&
        !isDataReadOnly.value &&
        !meta.value?.synced &&
        (!interfacePageDataApi || interfacePageDataApi.canAddDeleteInline.value)
      const tablePermitted = (key: PermissionKey) =>
        !!interfacePageDataApi || !meta.value?.id || isPermissionAllowed(PermissionEntity.TABLE, meta.value.id, key)

      if (
        canAddDeleteRows &&
        (interfacePageDataApi || (g.isOrderColumnExists.value && g.isPrimaryKeyAvailable.value)) &&
        tablePermitted(PermissionKey.TABLE_RECORD_ADD)
      ) {
        commands.push({
          id: 'record:duplicate',
          priority: CMD_PRIORITY.normal,
          title: t('labels.commandPalette.duplicateRecord'),
          section,
          icon: { type: 'icon', name: 'duplicate' },
          feedback: t('msg.success.rowDuplicated'),
          run: () => g.duplicateRow(context, { notify: false }),
        })
      }

      // Comments: the menu's "Add comment" gate; the box itself lives in the expanded form.
      if (rowId && !row.rowMeta.new && !interfacePageDataApi && isUIAllowed('commentEdit') && !isMobileMode.value) {
        commands.push(
          {
            id: 'record:add-comment',
            priority: CMD_PRIORITY.normal,
            title: t('labels.commandPalette.addComment'),
            section,
            icon: { type: 'icon', name: 'ncMessageCircle' },
            keywords: ['comment', 'note', 'discuss'],
            feedback: t('labels.commandPalette.commentAdded'),
            edit: {
              value: '',
              multiline: true,
              placeholder: t('labels.commandPalette.commentPlaceholder'),
              validate: (value) => (value.trim() ? undefined : t('labels.commandPalette.commentRequired')),
              submit: async (value) => {
                try {
                  await $api.internal.postOperation(
                    activeWorkspaceId.value!,
                    meta.value!.base_id!,
                    { operation: 'commentRow' },
                    { fk_model_id: meta.value!.id!, row_id: rowId, comment: value.trim().replace(/\n/g, '<br />') },
                  )
                } catch (e: unknown) {
                  throw new Error(await extractSdkResponseErrorMsg(e as Error & { response?: unknown }))
                }
                row.rowMeta.commentCount = (row.rowMeta.commentCount ?? 0) + 1
                g.triggerRefreshCanvas()
              },
            },
          },
          {
            id: 'record:open-comments',
            priority: CMD_PRIORITY.normal,
            title: t('labels.commandPalette.openComments'),
            section,
            icon: { type: 'icon', name: 'ncMessageCircle' },
            run: () => {
              // As the menu's "Add comment": the form opens on its comment box.
              isExpandedFormCommentMode.value = true
              g.expandForm(row, {}, false, path)
            },
          },
        )
      }

      if (canAddDeleteRows && tablePermitted(PermissionKey.TABLE_RECORD_DELETE)) {
        commands.push({
          id: 'record:delete',
          title: t('labels.commandPalette.deleteRecord'),
          section,
          icon: { type: 'icon', name: 'delete' },
          danger: true,
          // `notify: false` throws instead of toasting, so a failure must show in the row.
          feedback: t('labels.commandPalette.recordDeleted'),
          // Deletes immediately, as the menu's "Delete record" does (undo restores it).
          run: async () => {
            await g.deleteRow?.(cell.row!, path, { notify: false })
            // As the menu's confirmDeleteRow: only a selection covering the deleted row is cleared.
            if (selection.value.isRowInRange(cell.row!)) selection.value.clear()
            activeCell.value.row = -1
            activeCell.value.column = -1
          },
        })
      }

      commands.push(...(extras?.commands ?? []))

      // Button and AI fields: the same action a click on the cell runs, with its disabled states.
      if (rowId && !row.rowMeta.new) {
        const canGenerate = isUIAllowed('dataEdit') && !isDataReadOnly.value && !g.readOnly.value
        for (const column of columns.value) {
          const columnObj = column.columnObj
          if (!columnObj?.id || column.isInvalidColumn?.isInvalid || g.actionManager.isLoading(rowId, column.id)) continue
          const isPrompt = isAIPromptCol(columnObj)
          if (isPrompt) {
            if (!canGenerate || column.readonly || columnObj.readonly) continue
            if (!(columnObj.colOptions as ButtonType)?.fk_integration_id) continue
          } else {
            const colOptions = columnObj.colOptions as ButtonType | undefined
            if (columnObj.uidt !== UITypes.Button || !colOptions?.type || row.rowMeta.buttonDisabled?.[column.id]) continue
            if (colOptions.type === 'url' && !row.row[columnObj.title!]?.url) continue
            if (colOptions.type === 'script' && interfacePageDataApi) continue
            if (colOptions.type === 'workflow' && interfacePageDataApi && !interfacePageDataApi.triggerButtonWorkflow) continue
            if (colOptions.type === 'ai' && !colOptions.fk_integration_id) continue
          }
          commands.push({
            id: `record:run:${columnObj.id}`,
            priority: CMD_PRIORITY.normal,
            title: t(isPrompt ? 'labels.commandPalette.generateField' : 'labels.commandPalette.runButton', {
              field: columnObj.title,
            }),
            section,
            icon: { type: 'field', column: columnObj },
            keywords: ['run', 'click', 'button', 'generate', (columnObj.colOptions as ButtonType)?.label ?? ''],
            run: () =>
              g.actionManager.executeButtonAction([rowId], column, {
                row: [row],
                path,
                isAiPromptCol: isPrompt,
                allowLocalUrl: appInfo.value?.allowLocalUrl,
              }),
          })
        }
      }

      // The active cell's copy / clear, gated like the cell context menu's items.
      const cellColumn = cell.column !== undefined && cell.column >= 0 ? columns.value[cell.column] : undefined
      const cellColumnObj = cellColumn?.columnObj
      if (cellColumn && cellColumnObj && (selection.value.isEmpty() || selection.value.isSingleCell())) {
        commands.push({
          id: 'cell:copy',
          priority: CMD_PRIORITY.normal,
          title: t('labels.commandPalette.copyCell', { field: cellColumnObj.title }),
          section,
          icon: { type: 'icon', name: 'copy' },
          keywords: ['cell', 'value', 'clipboard'],
          feedback: t('labels.commandPalette.copied'),
          run: () => g.copyValue({ row: cell.row!, col: cell.column! }, path, { notify: false }),
        })

        const canClear =
          isUIAllowed('dataEdit') &&
          !g.readOnly.value &&
          !isDataReadOnly.value &&
          !meta.value?.synced &&
          cellColumn.isCellEditable &&
          !cellColumn.isSyncedColumn &&
          !row.rowMeta.isRlsHidden &&
          !cellColumnObj.readonly &&
          (isLinksOrLTAR(cellColumnObj) ||
            (!isVirtualCol(cellColumnObj) && !isSystemColumn(cellColumnObj) && !isAutoGeneratedColumn(cellColumnObj))) &&
          isPermissionAllowed(PermissionEntity.FIELD, cellColumnObj.id!, PermissionKey.RECORD_FIELD_EDIT)
        if (canClear) {
          commands.push({
            id: 'cell:clear',
            priority: CMD_PRIORITY.normal,
            title: t('labels.commandPalette.clearCell', { field: cellColumnObj.title }),
            section,
            icon: { type: 'icon', name: 'ncX' },
            keywords: ['cell', 'empty', 'remove', 'value'],
            run: async () => {
              await g.clearCell({ row: cell.row!, col: cell.column!, path })
              g.triggerRefreshCanvas()
            },
          })
        }
      }

      // The cell's own Set / Copy / Clear <field> lead the record's rows (link-field:, unlink-field: too).
      const isOwn = (command: CmdCommand) =>
        command.id.startsWith('cell:') || (!!cellColumnObj?.id && command.id.endsWith(`-field:${cellColumnObj.id}`))
      const ordered = [
        ...commands.filter(isOwn).map((command) => ({ ...command, priority: CMD_PRIORITY.primary })),
        ...commands.filter((command) => !isOwn(command)),
      ]

      const displayColumn = (meta.value?.columns as ColumnType[] | undefined)?.find((c) => c.pv)
      const recordLabel = (displayColumn && String(row.row[displayColumn.title!] ?? '')) || String(rowId ?? '')
      return {
        // Names the cell: "<record> › <field>"; the table chip is one Backspace away.
        context: cellColumnObj
          ? {
              prefix: recordLabel || meta.value?.title,
              label: cellColumnObj.title ?? '',
              icon: { type: 'field', column: cellColumnObj },
            }
          : {
              prefix: meta.value?.title,
              label: recordLabel,
              icon: { type: 'table', icon: parseProp(meta.value?.meta).icon },
            },
        commands: ordered,
        fallbacks: extras?.fallbacks,
      }
    },
  )
}
